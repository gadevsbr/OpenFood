  await p.locator("#subtabCombos").click();
  await p.locator("#comboForm").evaluate((f) => f.closest("details").open = true);
  const name = "Combo almoço QA " + suffix;
  await p.locator("#comboForm [name=name]").fill(name);
  await p.locator("#comboForm [name=price]").fill("35,01");
  await p.locator("#comboForm [name=active]").check();
  await p.locator("#comboForm button[type=submit]").click();
  await p.locator("#combosTable tr").filter({ hasText: name }).waitFor();
  const combo = (await read("combos")).find((c) => c.name === name);
  for (const [id, optional] of [[burger, false], [drink, true]]) await write("combo-items?combo_id=" + combo.id, { product_id: id, quantity: 1, is_optional: optional, group_name: optional ? "Bebida" : "", min_selections: optional ? 1 : 0, max_selections: 1 });
  await p.locator("#combosTable tr").filter({ hasText: name }).getByRole("button", { name: "Editar", exact: true }).click();
  await p.locator("#comboForm [name=description]").fill("Sanduíche e bebida · QA");
  await p.locator("#comboSubmit").click();
  await p.locator("#comboSubmit").filter({ hasText: "Salvar combo" }).waitFor();
  await shot("combo-admin");
  await p.locator("#adminToPOS").click();
  await p.waitForFunction(() => !posBusy);
  if (await p.locator("#posCashGate").isVisible()) {
    await p.locator("#posOpenForm [name=opening]").fill("0,00");
    await p.locator("#posOpenSubmit").click();
    await p.locator("#posCashGate").waitFor({ state: "hidden" });
  }
  await p.locator("#posCustomerSection").evaluate(el=>el.open=true);
  await p.locator("#posCustomer").selectOption(String(customer));
  await p.locator('#posGrid button[data-combo-id="' + combo.id + '"]').click();
  await p.locator("#comboChoiceForm button[type=submit]").click();
  await p.locator("#comboChoiceForm [role=alert]:not(.hidden)").waitFor();
  await p.locator("#comboChoiceForm select").selectOption(String(cfg.variants[0].id));
  await p.locator("#comboChoiceForm [name=addon]").check();
  await p.locator("#comboChoiceForm [name=component]").last().check();
  await p.locator("#comboChoiceForm textarea").first().fill("Sem cebola QA");
  await p.locator("#comboChoiceForm [name=quantity]").fill("2");
  await shot("combo-choices-desktop");
  await p.setViewportSize({ width: 390, height: 844 });
  await shot("combo-choices-mobile");
  assert(await p.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await p.locator("#comboChoiceForm button[type=submit]").click();
  await p.locator("#posDialog").waitFor({ state: "hidden" });
  await p.locator("#posMobileCart").click();
  assert((await p.locator("#posTotal").textContent()).includes("86,02"));
  await shot("combo-cart-mobile");
  await p.reload();
  await p.locator("#enterPOS").click();
  await p.waitForFunction(()=>!posBusy);
  assert.equal(await p.locator("#posCustomer").inputValue(),String(customer));
  assert.equal(await p.locator("#posCartLines .pos-line").count(),1);
  await p.locator("#posMobileCart").click();
  await p.locator("#posPay").click();
  await p.locator("#posPaymentRows select").selectOption("card");
  await p.locator("#posPaymentForm [name=confirmed]").check();
  await p.locator("#posConfirmSale").click();
  await p.locator(".pos-receipt").waitFor();
  assert((await p.locator(".pos-receipt").textContent()).includes("Sem cebola QA"));
  await shot("combo-receipt-mobile");
  const exported = await read("customer-export?customer_id=" + customer);
  assert.equal(exported.orders.length, 1);
  assert.equal(exported.orders[0].total_cents, 8602);
  assert(exported.items[0].selection.combo.components.some((c) => c.notes === "Sem cebola QA"));
  const after = await read("products");
  assert.equal(after.find((p2) => p2.id === burger).stock_quantity, 98);
  assert.equal(after.find((p2) => p2.id === drink).stock_quantity, 98);
  await p.getByRole("button", { name: "Nova venda", exact: true }).click();
  await p.setViewportSize({ width: 1440, height: 1e3 });
  await p.locator("#posTheme").selectOption("dark");
  await p.locator('#posGrid button[data-combo-id="' + combo.id + '"]').click();
  await shot("combo-choices-dark");
  await p.keyboard.press("Escape");
  await p.locator("#posTheme").selectOption("light");
  await p.locator("#posToAdmin").click();
  await p.locator("#tabClientes").click();
  await p.locator("#customersTable tr").filter({ hasText: "Cliente combo QA " + suffix }).getByRole("button", { name: "Histórico", exact: true }).click();
  await p.locator("#posDialog").waitFor({ state: "visible" });
  assert((await p.locator("#posDialog").textContent()).includes("86,02"));
  await shot("customer-history");
  await p.keyboard.press("Escape");
  await p.locator("#subtabConsentimentos").click();
  await p.locator("#consentForm").evaluate((f) => f.closest("details").open = true);
  await p.locator("#consentForm [name=customer_id]").selectOption(String(customer));
  await p.locator("#consentForm [name=purpose]").fill("marketing_email");
