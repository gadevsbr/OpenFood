  const customer = (await write("customers", { name: "Cliente combo QA " + suffix, phone: "5511" + String(suffix).slice(-9), email: `combo-${suffix}@example.org`, notes: "Observação privada QA" })).id;
  const cfg = await write("product-configuration?product_id=" + burger, { product_id: burger, version: 1, variants: [{ id: 0, name: "Grande", price_adjustment_cents: 500, stock_quantity: 100, active: true }], groups: [{ id: 0, name: "Adicionais", min_selections: 1, max_selections: 1, required: true, active: true, options: [{ id: 0, name: "Bacon", price_cents: 300, stock_quantity: 100, active: true }] }] });
